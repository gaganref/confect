it.effect(
  "pauses the watcher before rollback removes output and resumes after rejection",
  () =>
    Effect.gen(function* () {
      const services23 = yield* Layer.build(NodeServices.layer);
      return yield* Effect.gen(function* () {
        const project = yield* Project.makeNodeComponent;
        const fs = yield* FileSystem.FileSystem;
        const paths = yield* Path.Path;
        const generated = paths.join(project.root, "confect", "_generated");
        const lifecycle: string[] = [];
        let watching = true;
        const duringRestore = Effect.acquireRelease(
          Effect.sync(() => {
            watching = false;
            lifecycle.push("pause");
          }),
          () =>
            Effect.sync(() => {
              watching = true;
              lifecycle.push("resume");
            }),
        );
        const guardedFs = FileSystem.FileSystem.of({
          ...fs,
          remove: (path, options) =>
            Effect.suspend(() => {
              if (path === generated) {
                if (watching)
                  return Effect.fail(
                    PlatformError.systemError({
                      _tag: "PermissionDenied",
                      module: "FileSystem",
                      method: "remove",
                      pathOrDescriptor: path,
                    }),
                  );
                lifecycle.push("remove");
              }
              return fs.remove(path, options);
            }),
        });
        const result = yield* Effect.gen(function* () {
          const services24 = yield* Layer.build(
            DirectoryOptions.layer({
              componentDir: Option.some(`${project.root}/convex`),
            }),
          );
          return yield* makeCodegenHandler(duringRestore).pipe(
            Effect.provideContext(services24),
          );
        }).pipe(
          Effect.scoped,
          Effect.provideService(FileSystem.FileSystem, guardedFs),
          Effect.result,
        );
        assertIs(result, Result.isFailure);
        expect(result.failure).toMatchObject({
          _tag: "ComponentNodeGroupError",
          groupPath: "tasks",
        });
        expect(lifecycle).toEqual(["pause", "remove", "resume"]);
        expect(watching).toBe(true);
        const generatedExists = yield* fs.exists(generated);
        expect(generatedExists).toBe(false);
      }).pipe(Effect.scoped, Effect.provideContext(services23));
    }),
);

