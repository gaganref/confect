it.effect.each([
  { change: "unchanged", status: "" },
  { change: "edited", status: " M convex/.gitignore\n" },
  { change: "deleted", status: "?? convex/.gitignore\n" },
] as const)(
  "rewrites a committed component .gitignore that is $change, so the committed-codegen check sees any change",
  ({ change, status }) =>
    Effect.gen(function* () {
      const platform = yield* Layer.build(NodeServices.layer);
      return yield* Effect.gen(function* () {
        const fs = yield* FileSystem.FileSystem;
        const directory = yield* committedComponent;
        if (change === "edited") {
          yield* fs.writeFileString(
            `${directory}/convex/.gitignore`,
            "node_modules/\n",
          );
          yield* git(directory, "commit", "-qam", "edit");
        }
        if (change === "deleted") {
          yield* git(directory, "rm", "-q", "convex/.gitignore");
          yield* git(directory, "commit", "-qm", "delete");
        }
        yield* generateComponent(directory);
        const after = yield* git(directory, "status", "--porcelain", "--", ".");
        expect(after).toBe(status);
        const restored = yield* fs.readFileString(
          `${directory}/convex/.gitignore`,
        );
        expect(restored).toBe(componentIgnore);
      }).pipe(Effect.scoped, Effect.provideContext(platform));
    }),
  { timeout: 30000 },
);

