const componentIgnore =
  "# Generated by `confect codegen`. Do not edit.\n# Convex writes _generated/ here on each push.\n/_generated/\n";

/**
 * Run git in `cwd` with no global or system configuration, so a developer's
 * signing, hooks or line-ending settings cannot change the result.
 */
const git = Effect.fnUntraced(function* (
  cwd: string,
  ...args: ReadonlyArray<string>
) {
  const path = yield* Path.Path;
  const spawner = yield* ChildProcessSpawner;
  const handle = yield* spawner.spawn(
    ChildProcess.make(
      "git",
      [
        "-c",
        "user.name=Confect",
        "-c",
        "user.email=confect@example.com",
        "-c",
        "commit.gpgsign=false",
        ...args,
      ],
      {
        cwd,
        env: {
          GIT_CONFIG_GLOBAL: path.join(cwd, ".git", "no-global-config"),
          GIT_CONFIG_NOSYSTEM: "1",
        },
        extendEnv: true,
        stdin: "ignore",
      },
    ),
  );
  const [stdout, exitCode] = yield* Effect.all(
    [handle.stdout.pipe(Stream.decodeText(), Stream.mkString), handle.exitCode],
    { concurrency: "unbounded" },
  );
  expect(exitCode, `git ${Array.join(args, " ")}`).toBe(0);
  return stdout;
}, Effect.scoped);

