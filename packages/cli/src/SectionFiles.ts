import type { FunctionSpec, GroupSpec, ManifestSection } from "@confect/core";
import * as Effect from "effect/Effect";
import * as FileSystem from "effect/FileSystem";
import * as Path from "effect/Path";
import * as Result from "effect/Result";
import * as Schema from "effect/Schema";
import { fromBundlerError } from "./BuildError.js";
import * as Bundler from "./Bundler.js";
import {
  InvalidManifestSectionError,
  logCodegenError,
} from "./CodegenError.js";
import { ConfectDirectory } from "./ConfectDirectory.js";
import type { LoadedLeafModule } from "./LeafModule.js";
import { logFileRemoved } from "./log.js";
import {
  removePathIfExists,
  toPosixPath,
  writeFileStringAndLog,
} from "./utils.js";

type Leaf = Pick<LoadedLeafModule, "spec" | "pathSegments" | "relativePath">;

/**
 * The files codegen writes directly in `confect/_generated`, current and
 * legacy, which no section may claim.
 */
export const builtIn: ReadonlySet<string> = new Set(
  `spec schema convexSchema id components component refs docs services manifest
  auth.providers testing api nodeApi impl nodeImpl nodeSpec registeredFunctions
  nodeRegisteredFunctions`
    .split(/\s+/)
    .map((name) => `${name}.ts`),
);

const PREFIX = "// Generated by `confect codegen` from the manifest section ";
const header = (key: string) => `${PREFIX}${JSON.stringify(key)}. Do not edit.`;
const encodeSources = Schema.encodeSync(
  Schema.fromJsonString(Schema.Array(Schema.String)),
);

interface Claim {
  readonly key: string;
  readonly generate: ManifestSection.Generate;
}

const visit = (
  leaves: ReadonlyArray<Leaf>,
  each: (spec: FunctionSpec.AnyWithProps, path: string, source: string) => void,
) => {
  const walk = (
    group: GroupSpec.AnyWithProps,
    path: string,
    source: string,
  ) => {
    for (const spec of Object.values(group.functions))
      each(spec, `${path}:${spec.name}`, source);
    for (const [name, child] of Object.entries(group.groups))
      walk(child, `${path}/${name}`, source);
  };
  for (const leaf of leaves)
    walk(leaf.spec, leaf.pathSegments.join("/"), leaf.relativePath);
};

/**
 * One claim per section key that generates a file, ordered by file. A name that
 * is built in, not a `.ts` file directly in `_generated`, or claimed by two
 * keys is refused.
 */
export const claims = (leaves: ReadonlyArray<Leaf>) =>
  Result.gen(function* () {
    const byKey = new Map<string, ManifestSection.Generate>();
    visit(leaves, (spec) => {
      for (const { key, section } of spec.manifestSections ?? [])
        if (section.generate !== undefined && !byKey.has(key))
          byKey.set(key, section.generate);
    });
    const byFile = new Map<string, string>();
    for (const [key, { file }] of byKey) {
      const other = byFile.get(file);
      const refusal = builtIn.has(file)
        ? `claims confect/_generated/${file}, which codegen writes itself.`
        : !/^[\w-]+\.ts$/.test(file)
          ? `claims ${JSON.stringify(file)}; name a .ts file directly inside confect/_generated.`
          : other !== undefined
            ? `claims confect/_generated/${file}, which the manifest section ${JSON.stringify(other)} also claims.`
            : undefined;
      if (refusal !== undefined)
        return yield* Result.fail(
          new InvalidManifestSectionError({ sectionKey: key, reason: refusal }),
        );
      byFile.set(file, key);
    }
    return [...byKey]
      .map(([key, generate]) => ({ key, generate }))
      .sort((a, b) => a.generate.file.localeCompare(b.generate.file));
  });

const sourceFiles = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  return (yield* fs.readDirectory(confectDirectory, { recursive: true }))
    .map((file) => toPosixPath(path, file))
    .filter(
      (file) =>
        file.endsWith(".ts") &&
        !file.endsWith(".d.ts") &&
        !file.split("/").includes("_generated"),
    )
    .sort();
});

const render = Effect.fnUntraced(function* (
  { key, generate }: Claim,
  input: Omit<ManifestSection.GenerateInput, "modules">,
  files: ReadonlyArray<string>,
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const failed = (cause: unknown) =>
    new InvalidManifestSectionError({
      sectionKey: key,
      reason: `generate failed: ${String(cause)}`,
    });
  const matched = yield* Effect.try({
    try: () => files.filter((file) => generate.match(file)),
    catch: failed,
  });
  const modules = yield* Effect.forEach(matched, (relativePath) =>
    Bundler.bundle(path.join(confectDirectory, relativePath)).pipe(
      Effect.map(({ module }) => ({ relativePath, exports: module })),
      Effect.mapError((error) =>
        fromBundlerError(`confect/${relativePath}`, error),
      ),
    ),
  );
  const { contents, errors } = yield* Effect.try({
    try: () => generate.render({ ...input, modules }),
    catch: failed,
  });
  const [error, ...more] = errors.map(
    (reason) => new InvalidManifestSectionError({ sectionKey: key, reason }),
  );
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
  return [header(key), `// Sources: ${encodeSources(matched)}`, contents].join(
    "\n",
  );
});

/**
 * The files in `confect/_generated` a section wrote, which carry its header.
 */
export const written = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const generated = path.join(yield* ConfectDirectory.get, "_generated");
  if (!(yield* fs.exists(generated))) return [];
  return yield* Effect.filter(
    (yield* fs.readDirectory(generated)).filter((file) => file.endsWith(".ts")),
    (file) =>
      fs
        .readFileString(path.join(generated, file))
        .pipe(Effect.map((contents) => contents.startsWith(PREFIX))),
  );
});

/**
 * Write each claimed file into `confect/_generated` once every section has
 * rendered, and remove a file a section wrote that no section claims any more.
 * Every section renders before codegen fails with the first error after logging
 * the rest. Returns the claimed file names and whether they differ from the
 * section files that existed before.
 */
export const sync = Effect.fnUntraced(function* (
  leaves: ReadonlyArray<Leaf>,
  mounts: ManifestSection.GenerateInput["mounts"],
) {
  const path = yield* Path.Path;
  const generated = path.join(yield* ConfectDirectory.get, "_generated");
  const claimed = yield* Effect.fromResult(claims(leaves));
  const functions: Array<{ path: string; source: string }> = [];
  visit(leaves, (_, functionPath, source) =>
    functions.push({ path: functionPath, source }),
  );
  const files = claimed.length === 0 ? [] : yield* sourceFiles;
  const [rendered, failures] = yield* Effect.partition(claimed, (claim) =>
    render(claim, { functions, mounts }, files).pipe(
      Effect.map((contents) => ({ file: claim.generate.file, contents })),
    ),
  );
  const [error, ...more] = failures;
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
  const existing = yield* written;
  for (const { file, contents } of rendered)
    yield* writeFileStringAndLog(path.join(generated, file), contents);
  const names = rendered.map(({ file }) => file);
  for (const file of existing)
    if (!names.includes(file)) {
      yield* removePathIfExists(path.join(generated, file));
      yield* logFileRemoved(path.join(generated, file));
    }
  return {
    files: names,
    changed:
      names.length !== existing.length ||
      names.some((file) => !existing.includes(file)),
  };
});
