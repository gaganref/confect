type Leaf = Pick<LoadedLeafModule, "spec" | "pathSegments" | "relativePath">;

/**
 * The files codegen writes directly in `confect/_generated`, current and
 * legacy, which no section may claim.
 */
export const builtIn: ReadonlySet<string> = new Set(
  Arr.map(
    pipe(
      `spec schema convexSchema id components component refs docs services manifest
  auth.providers testing api nodeApi impl nodeImpl nodeSpec registeredFunctions
  nodeRegisteredFunctions`,
      Str.split(/\s+/),
    ),
    (name) => `${name}.ts`,
  ),
);

const PREFIX = "// Generated by `confect codegen` from the manifest section ";
const header = (key: string) => `${PREFIX}${JSON.stringify(key)}. Do not edit.`;
const Sources = Schema.String.pipe(Schema.Array, Schema.fromJsonString);
const encodeSources = Schema.encodeSync(Sources);
const decodeSources = Schema.decodeUnknownOption(Sources);
const INPUTS = "sectionInputs.json";
const VERIFY_INPUTS = "verifyInputs.json";

interface Claim {
  readonly key: string;
  readonly generate: ManifestSection.Generate;
}

/**
 * A declared backend: the target codegen generates and the sections its
 * `App.make` names.
 */
export interface Backend {
  readonly target: ManifestSection.Target;
  readonly sections: ReadonlyArray<ManifestSection.Entry>;
}

const visit = (
  leaves: ReadonlyArray<Leaf>,
  each: (spec: FunctionSpec.AnyWithProps, path: string, source: string) => void,
) => {
  const walk = (
    group: GroupSpec.AnyWithProps,
    path: string,
    source: string,
  ) => {
    for (const spec of Record.values(group.functions))
      each(spec, `${path}:${spec.name}`, source);
    for (const [name, child] of Record.toEntries(group.groups))
      walk(child, `${path}/${name}`, source);
  };
  for (const leaf of leaves)
    walk(leaf.spec, Arr.join(leaf.pathSegments, "/"), leaf.relativePath);
};

/**
 * One claim per declared section that generates a file, ordered by file. A name
 * that is built in, not a `.ts` file directly in `_generated`, or claimed by
 * two keys is refused.
 */
export const claims = (sections: ReadonlyArray<ManifestSection.Entry>) =>
  Result.gen(function* () {
    const byKey = new Map<string, ManifestSection.Generate>();
    for (const { key, section } of sections)
      if (section.generate !== undefined) byKey.set(key, section.generate);
    const byFile = new Map<string, string>();
    for (const [key, { file }] of byKey) {
      const other = byFile.get(file);
      const refusal = builtIn.has(file)
        ? `claims confect/_generated/${file}, which codegen writes itself.`
        : !/^[\w-]+\.ts$/.test(file)
          ? `claims ${JSON.stringify(file)}; name a .ts file directly inside confect/_generated.`
          : other !== undefined
            ? `claims confect/_generated/${file}, which the manifest section ${JSON.stringify(other)} also claims.`
            : undefined;
      if (refusal !== undefined)
        return yield* Result.fail(
          InvalidManifestSectionError.make({
            sectionKey: key,
            reason: refusal,
          }),
        );
      byFile.set(file, key);
    }
    return Arr.map([...byKey], ([key, generate]) => ({ key, generate })).sort(
      (a, b) => pipe(a.generate.file, Str.localeCompare(b.generate.file)),
    );
  });

const sourceFiles = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const directory = yield* fs.readDirectory(confectDirectory, {
    recursive: true,
  });
  return pipe(
    directory,
    Arr.map((file) => toPosixPath(path, file)),
    Arr.filter(
      (file) =>
        pipe(file, Str.endsWith(".ts")) &&
        !pipe(file, Str.endsWith(".d.ts")) &&
        !pipe(file, Str.split("/")).includes("_generated"),
    ),
  ).sort();
});

/**
 * Bundle each matched `confect/` file and return its exports, adding it and
 * every first-party file it imports to `watched`.
 */
const load = Effect.fnUntraced(function* (
  matched: ReadonlyArray<string>,
  watched: Set<string>,
  plugins: ReadonlyArray<esbuild.Plugin> = [],
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  for (const file of matched) watched.add(file);
  return yield* Effect.forEach(matched, (relativePath) => {
    const entry = path.join(confectDirectory, relativePath);
    // Inputs are recorded once esbuild finishes, before the module runs, so a
    // module that throws on load still has its imports watched. `confect dev`
    // sees changes only under `confect/`, and every run rewrites `_generated`,
    // so watching it would loop.
    const recordInputs: esbuild.Plugin = {
      name: "confect:section-inputs",
      setup: (build) =>
        build.onEnd(({ metafile }) => {
          for (const loaded of Record.keys(metafile?.inputs ?? {})) {
            // A plugin's own namespace, such as the component config
            // wrapper, is not a file.
            if (/^[^/\\]+:/.test(loaded) && !path.isAbsolute(loaded)) continue;
            const file = toPosixPath(
              path,
              path.relative(
                confectDirectory,
                path.resolve(path.dirname(entry), loaded),
              ),
            );
            if (
              !pipe(file, Str.startsWith("../")) &&
              !pipe(file, Str.startsWith("_generated/"))
            )
              watched.add(file);
          }
        }),
    };
    return Bundler.bundle(entry, { plugins: [...plugins, recordInputs] }).pipe(
      Effect.mapBoth({
        onFailure: (error) =>
          fromBundlerError(`confect/${relativePath}`, error),
        onSuccess: ({ module }) => ({ relativePath, exports: module }),
      }),
    );
  });
});

/**
 * Fail with the first of a section's refusals after logging the rest.
 */
const refuse = Effect.fnUntraced(function* (
  key: string,
  reasons: ReadonlyArray<string>,
) {
  const [error, ...more] = Arr.map(reasons, (reason) =>
    InvalidManifestSectionError.make({ sectionKey: key, reason }),
  );
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
});

const render = Effect.fnUntraced(function* (
  { key, generate }: Claim,
  target: ManifestSection.Target,
  input: Pick<ManifestSection.GenerateInput, "functions" | "mounts" | "files">,
  watched: Set<string>,
) {
  const confectDirectory = yield* ConfectDirectory.get;
  const failed = (cause: unknown) =>
    InvalidManifestSectionError.make({
      sectionKey: key,
      reason: `generate failed: ${String(cause)}`,
    });
  const matched = yield* Effect.try({
    try: () => Arr.filter(input.files, (file) => generate.match(file)),
    catch: failed,
  });
  const modules = yield* load(matched, watched);
  const { contents, errors } = yield* Effect.try({
    try: () => generate.render({ ...input, modules, target, confectDirectory }),
    catch: failed,
  });
  yield* refuse(key, errors);
  return {
    modules,
    contents: Arr.join(
      [header(key), `// Sources: ${encodeSources(matched)}`, contents],
      "\n",
    ),
  };
});

/**
 * The files in `confect/_generated` a section wrote, which carry its header.
 *
 * @internal
 */
export const written = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  if (!(yield* fs.exists(generated))) return [];
  const directory = yield* fs.readDirectory(generated);
  return yield* Effect.filter(
    Arr.filter(directory, (file) => pipe(file, Str.endsWith(".ts"))),
    (file) =>
      fs
        .readFileString(path.join(generated, file))
        .pipe(Effect.map((contents) => pipe(contents, Str.startsWith(PREFIX)))),
  );
});

const record = Effect.fnUntraced(function* (name: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const file = path.join(confectDirectory, "_generated", name);
  const none: ReadonlyArray<string> = [];
  if (!(yield* fs.exists(file))) return none;
  const fileContents = yield* fs.readFileString(file);
  return Option.getOrElse(decodeSources(fileContents), () => none);
});

/**
 * The `confect/` files the declared sections' `generate` and `verify` matched
 * and the `confect/` files those import, as recorded by the last codegen run
 * that loaded them.
 *
 * @internal
 */
export const inputs = Effect.map(
  Effect.all([record(INPUTS), record(VERIFY_INPUTS)]),
  ([rendered, verified]) => [...new Set([...rendered, ...verified])].sort(),
);

/**
 * Write each claimed file into `confect/_generated` once every section the
 * declared backend names has rendered for its target; an undeclared backend
 * renders none. Every section renders before codegen fails with the first error
 * after logging the rest. The record of section inputs is written either way,
 * keeping the previous inputs after a failure, so `confect dev` sees the fix.
 * Returns the claimed file names, whether they differ from the section files
 * that existed before, and the modules each section key matched.
 */
export const sync = Effect.fnUntraced(function* (
  backend: Option.Option<Backend>,
  leaves: ReadonlyArray<Leaf>,
  mounts: ManifestSection.GenerateInput["mounts"],
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  const claimed = Option.isSome(backend)
    ? yield* Effect.map(
        Effect.fromResult(claims(backend.value.sections)),
        Arr.map((claim) => ({ claim, target: backend.value.target })),
      )
    : [];
  const functions: Array<{ path: string; source: string }> = [];
  visit(leaves, (_, functionPath, source) =>
    functions.push({ path: functionPath, source }),
  );
  const files = claimed.length === 0 ? [] : yield* sourceFiles;
  const watched = new Set<string>();
  const [rendered, failures] = yield* Effect.partition(
    claimed,
    ({ claim, target }) =>
      render(claim, target, { functions, mounts, files }, watched).pipe(
        Effect.map((output) => ({ ...claim, ...output })),
      ),
  );
  if (failures.length > 0)
    for (const file of yield* record(INPUTS)) watched.add(file);
  yield* claimed.length === 0
    ? removePathIfExists(path.join(generated, INPUTS))
    : writeFileStringAndLog(
        path.join(generated, INPUTS),
        encodeSources([...watched].sort()),
      );
  const [error, ...more] = failures;
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
  const existing = yield* written;
  for (const { generate, contents } of rendered)
    yield* writeFileStringAndLog(path.join(generated, generate.file), contents);
  const names = Arr.map(rendered, ({ generate }) => generate.file);
  return {
    modules: new Map(Arr.map(rendered, ({ key, modules }) => [key, modules])),
    files: names,
    changed:
      names.length !== existing.length ||
      Arr.some(names, (file) => !existing.includes(file)),
  };
});

/**
 * Run each declared section's `verify` once every `_generated` file exists:
 * bundle the `confect/` files its `match` selects as codegen bundles a
 * declaration, and hand their exports, the mounts and the target to its
 * `check`. Every section checks before codegen fails with the first refusal
 * after logging the rest. The files each loaded are recorded as section inputs,
 * keeping the previous ones after a failure, so `confect dev` checks again when
 * one changes.
 */
export const verify = Effect.fnUntraced(function* (
  backend: Option.Option<Backend>,
  mounts: ManifestSection.VerifyInput["mounts"],
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const recorded = path.join(confectDirectory, "_generated", VERIFY_INPUTS);
  const checks = Option.match(backend, {
    onNone: () => [],
    onSome: ({ sections }) =>
      Arr.flatMap(sections, ({ key, section }) =>
        section.generate?.verify === undefined
          ? []
          : [{ key, verifier: section.generate.verify }],
      ),
  });
  if (Option.isNone(backend) || checks.length === 0)
    return yield* removePathIfExists(recorded);
  const { target } = backend.value;
  const files = yield* sourceFiles;
  const watched = new Set<string>();
  const [, failures] = yield* Effect.partition(checks, ({ key, verifier }) =>
    Effect.gen(function* () {
      const failed = (cause: unknown) =>
        InvalidManifestSectionError.make({
          sectionKey: key,
          reason: `verify failed: ${String(cause)}`,
        });
      const matched = yield* Effect.try({
        try: () => Arr.filter(files, (file) => verifier.match(file)),
        catch: failed,
      });
      const modules = yield* load(matched, watched, [
        ConvexConfig.componentConfigPlugin(path),
      ]);
      const tryValue = yield* Effect.try({
        try: () => verifier.check({ modules, mounts, target }),
        catch: failed,
      });
      yield* refuse(key, tryValue);
    }),
  );
  if (failures.length > 0)
    for (const file of yield* record(VERIFY_INPUTS)) watched.add(file);
  yield* writeFileStringAndLog(recorded, encodeSources([...watched].sort()));
  const [error, ...more] = failures;
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
});

/**
 * Remove each file a section wrote that is not in `files`. Codegen runs this
 * after it rewrites the registration files and the HTTP router, so a run that
 * fails earlier leaves no import of a removed file.
 */
export const removeUnclaimed = Effect.fnUntraced(function* (
  files: ReadonlyArray<string>,
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  for (const file of yield* written)
    if (!files.includes(file)) {
      yield* removePathIfExists(path.join(generated, file));
      yield* logFileRemoved(path.join(generated, file));
    }
});
