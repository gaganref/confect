type SectionFunction = ManifestSection.GenerateInput["functions"][number];

type SectionFunctions = Pick<
  ManifestSection.GenerateInput,
  "functions" | "functionOf"
>;

const described = (value: unknown) =>
  typeof value === "object" &&
  value !== null &&
  "name" in value &&
  typeof value.name === "string"
    ? `the spec of ${quote(value.name)}`
    : "a value";

/**
 * Why `functionOf` found no function for `value`.
 */
const notLoaded = (value: unknown) =>
  `functionOf got ${described(value)}, which is not a spec codegen loaded. Likely causes: a module imported it in a way codegen could not bundle, such as through createRequire or a Module instance's require, an import() whose path is computed or that esbuild ignored, or a package in node_modules that re-exports a spec from confect/; or no group registers it.`;

/**
 * Why `functionOf` named no function for `value`, which more than one path
 * registers.
 */
const registeredTwice = (
  value: unknown,
  functions: ReadonlyArray<SectionFunction>,
) =>
  `functionOf got ${described(value)}, which is registered at ${functions.length} paths: ${pipe(
    functions,
    Arr.map((fn) => quote(fn.path)),
    Arr.sort(Order.String),
    Arr.join(", "),
  )}. A spec must be registered once for codegen to name its function.`;

/**
 * Every function and route spec the leaves declare, with its visibility, the
 * spec file declaring it, the key of its spec file's group and the spec itself,
 * and the lookup from a spec to its function, as a section's `render` and
 * `verify` get them. `functions` has one entry for each registration, so a spec
 * in two groups has two. `functionOf` throws for such a spec rather than name
 * one of them. `group` and `spec` are left out of the enumerable keys, so a
 * section that serializes a function writes what it wrote before functions
 * carried them. Given `unshared`, the reason the specs are not the objects the
 * section's modules import, reading `spec` and calling `functionOf` throw it
 * instead.
 */
const functionsOf = (
  leaves: ReadonlyArray<Leaf>,
  unshared?: string,
): SectionFunctions => {
  const functions: Array<SectionFunction> = [];
  const bySpec = new Map<unknown, Arr.NonEmptyArray<SectionFunction>>();
  const walk = (
    group: GroupSpec.AnyWithProps,
    path: string,
    source: string,
    key: string,
  ) => {
    for (const spec of Record.values(group.functions)) {
      const fn = Object.defineProperties(
        {
          path: `${path}:${spec.name}`,
          source,
          visibility: spec.functionVisibility,
        } as SectionFunction,
        {
          group: { value: key },
          spec:
            unshared === undefined
              ? { value: spec }
              : {
                  get: () => {
                    throw new Error(unshared);
                  },
                },
        },
      );
      functions.push(fn);
      const registered = bySpec.get(spec);
      if (registered === undefined) bySpec.set(spec, [fn]);
      else registered.push(fn);
    }
    for (const [name, child] of Record.toEntries(group.groups))
      walk(child, `${path}/${name}`, source, key);
  };
  for (const leaf of leaves) {
    const key = Arr.join(leaf.pathSegments, "/");
    walk(leaf.spec, key, leaf.relativePath, key);
  }
  return {
    functions,
    functionOf: (spec) => {
      if (unshared !== undefined) throw new Error(unshared);
      const registered = bySpec.get(spec);
      if (registered === undefined) throw new Error(notLoaded(spec));
      if (registered.length > 1)
        throw new Error(registeredTwice(spec, registered));
      return registered[0];
    },
  };
};

/**
 * One claim per declared section that generates a file, ordered by file. A name
 * that is built in, not a `.ts`, `.json` or `.md` file directly in
 * `_generated`, or claimed by two keys is refused, and so is a `.json` or `.md`
 * file that sets `importedByFunctions`, `wrapsCrons`, `wrapsSchema` or
 * `importedFirst`, as only a `.ts` file is imported. A second section that sets
 * `wrapsSchema` or `importedFirst` is refused, as is `importedFirst` with
 * `importedByFunctions: false`.
 */
export const claims = (sections: ReadonlyArray<ManifestSection.Entry>) =>
  Result.gen(function* () {
    const byKey = new Map<string, ManifestSection.Generate>();
    for (const { key, section } of sections)
      if (section.generate !== undefined) byKey.set(key, section.generate);
    const byFile = new Map<string, string>();
    // The key of the section that sets each option only one section may set.
    const sole = new Map<"wrapsSchema" | "importedFirst", string>();
    for (const [key, generate] of byKey) {
      const { file } = generate;
      const other = byFile.get(file);
      const imported = Arr.findFirst(
        [
          "importedByFunctions",
          "wrapsCrons",
          "wrapsSchema",
          "importedFirst",
        ] as const,
        (option) => generate[option] === true && !isModule(file),
      );
      const shared = Arr.head(
        Arr.flatMap(["wrapsSchema", "importedFirst"] as const, (option) => {
          const owner = sole.get(option);
          return generate[option] === true && owner !== undefined
            ? [{ option, owner }]
            : [];
        }),
      );
      const refusal = builtIn.has(file)
        ? `claims confect/_generated/${file}, which codegen writes itself.`
        : !NAME.test(file)
          ? `claims ${quote(file)}; name a .ts, .json or .md file directly inside confect/_generated.`
          : Option.isSome(imported)
            ? `sets ${imported.value} on confect/_generated/${file}, but only a .ts file is imported.`
            : other !== undefined
              ? `claims confect/_generated/${file}, which the manifest section ${quote(other)} also claims.`
              : Option.isSome(shared)
                ? `sets ${shared.value.option}, which the manifest section ${quote(shared.value.owner)} also sets; at most one section may.`
                : generate.importedFirst === true &&
                    generate.importedByFunctions === false
                  ? `sets importedFirst on confect/_generated/${file}, which importedByFunctions: false keeps out of registered functions.`
                  : undefined;
      if (refusal !== undefined)
        return yield* Result.fail(
          InvalidManifestSectionError.make({
            sectionKey: key,
            reason: refusal,
          }),
        );
      byFile.set(file, key);
      for (const option of ["wrapsSchema", "importedFirst"] as const)
        if (generate[option] === true) sole.set(option, key);
    }
    return Arr.map([...byKey], ([key, generate]) => ({ key, generate })).sort(
      (a, b) => pipe(a.generate.file, Str.localeCompare(b.generate.file)),
    );
  });

const sourceFiles = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const directory = yield* fs.readDirectory(confectDirectory, {
    recursive: true,
  });
  return pipe(
    directory,
    Arr.map((file) => toPosixPath(path, file)),
    Arr.filter(
      (file) =>
        pipe(file, Str.endsWith(".ts")) &&
        !pipe(file, Str.endsWith(".d.ts")) &&
        !pipe(file, Str.split("/")).includes("_generated"),
    ),
  ).sort();
});

/**
 * Whether a `confect/` file a matched file imports is a section input, which
 * `confect dev` watches. `confect dev` sees changes only under `confect/`, and
 * every run rewrites `_generated`, so watching it would loop.
 */
const isInput = (file: string) =>
  !pipe(file, Str.startsWith("../")) &&
  !pipe(file, Str.startsWith("_generated/"));

/**
 * Bundle `matched`, the `confect/` files a section matched, and every leaf spec
 * file as one module graph. Run the matched files in order, then the spec
 * files, each module once. Return each matched file's exports, and every
 * function with its spec as that graph evaluates it, so a spec a matched file
 * imports, directly or through other modules, is the very object its function
 * carries, and the lookup from a spec to its function. Each matched file and
 * every first-party file it imports is added to `watched`. When the files
 * cannot share a build, the build fails, or a package Node loads throws as it
 * initializes, each matched file is bundled on its own, which names a failing
 * file and records its inputs as before, and reading a function's spec or
 * calling `functionOf` throws why.
 */
const load = Effect.fnUntraced(function* (
  matched: ReadonlyArray<string>,
  leaves: ReadonlyArray<Leaf>,
  watched: Set<string>,
  plugins: ReadonlyArray<esbuild.Plugin> = [],
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  for (const file of matched) watched.add(file);
  if (matched.length === 0) return { modules: [], ...functionsOf(leaves) };
  const shared = yield* Bundler.bundleShared(
    Arr.map(
      [...matched, ...Arr.map(leaves, (leaf) => leaf.relativePath)],
      (file) => path.join(confectDirectory, file),
    ),
    plugins,
  ).pipe(Effect.result);
  if (Result.isFailure(shared)) {
    const { cause } = shared.failure;
    return {
      modules: yield* loadEach(matched, watched, plugins),
      ...functionsOf(
        leaves,
        `codegen could not bundle the files this section matched with the spec files in one build, so a function's spec is not the object they import: ${cause instanceof Error ? cause.message : String(cause)}`,
      ),
    };
  }
  const [entries, specs] = Arr.splitAt(shared.success, matched.length);
  const real = yield* Effect.orDie(fs.realPath(confectDirectory));
  const modules = yield* Effect.forEach(
    Arr.zip(matched, entries),
    ([relativePath, { metafile, warnings, module }]) =>
      Effect.gen(function* () {
        // Inputs are recorded before the module runs, so a module that
        // throws on load still has its imports watched.
        const inputs = yield* Effect.filter(
          Record.keys(metafile.inputs),
          (input) => Effect.orDie(fs.exists(input)),
        );
        for (const input of inputs) {
          const file = toPosixPath(path, path.relative(real, input));
          if (isInput(file)) watched.add(file);
        }
        return yield* module.pipe(
          Effect.ensuring(logCoalescedBuildWarnings(warnings)),
          Effect.mapBoth({
            onFailure: (error) =>
              fromBundlerError(`confect/${relativePath}`, error),
            onSuccess: (exports) => ({ relativePath, exports }),
          }),
        );
      }),
  );
  const evaluated = yield* Effect.forEach(
    Arr.zip(leaves, specs),
    ([leaf, { module }]) =>
      module.pipe(
        Effect.mapBoth({
          onFailure: (error) => fromBundlerError(leaf.relativePath, error),
          onSuccess: (exports) => ({ ...leaf, spec: exports.default }),
        }),
      ),
  );
  return { modules, ...functionsOf(evaluated) };
}, Effect.scoped);

/**
 * Bundle each matched `confect/` file on its own and return its exports, adding
 * it and every first-party file it imports to `watched`.
 */
const loadEach = Effect.fnUntraced(function* (
  matched: ReadonlyArray<string>,
  watched: Set<string>,
  plugins: ReadonlyArray<esbuild.Plugin>,
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  return yield* Effect.forEach(matched, (relativePath) => {
    const entry = path.join(confectDirectory, relativePath);
    // Inputs are recorded once esbuild finishes, before the module runs, so a
    // module that throws on load still has its imports watched.
    const recordInputs: esbuild.Plugin = {
      name: "confect:section-inputs",
      setup: (build) =>
        build.onEnd(({ metafile }) => {
          for (const loaded of Record.keys(metafile?.inputs ?? {})) {
            // A plugin's own namespace, such as the component config
            // wrapper, is not a file.
            if (/^[^/\\]+:/.test(loaded) && !path.isAbsolute(loaded)) continue;
            const file = toPosixPath(
              path,
              path.relative(
                confectDirectory,
                path.resolve(path.dirname(entry), loaded),
              ),
            );
            if (isInput(file)) watched.add(file);
          }
        }),
    };
    return Bundler.bundle(entry, { plugins: [...plugins, recordInputs] }).pipe(
      Effect.mapBoth({
        onFailure: (error) =>
          fromBundlerError(`confect/${relativePath}`, error),
        onSuccess: ({ module }) => ({ relativePath, exports: module }),
      }),
    );
  });
});

/**
 * Fail with the first of a section's refusals after logging the rest.
 */
const refuse = Effect.fnUntraced(function* (
  key: string,
  reasons: ReadonlyArray<string>,
) {
  const [error, ...more] = Arr.map(reasons, (reason) =>
    InvalidManifestSectionError.make({ sectionKey: key, reason }),
  );
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
});

const render = Effect.fnUntraced(function* (
  { key, generate }: Claim,
  target: ManifestSection.Target,
  leaves: ReadonlyArray<Leaf>,
  input: Pick<ManifestSection.GenerateInput, "mounts" | "files" | "sections">,
  watched: Set<string>,
) {
  const confectDirectory = yield* ConfectDirectory.get;
  const failed = (cause: unknown) =>
    InvalidManifestSectionError.make({
      sectionKey: key,
      reason: `generate failed: ${String(cause)}`,
    });
  const matched = yield* Effect.try({
    try: () => Arr.filter(input.files, (file) => generate.match(file)),
    catch: failed,
  });
  const { modules, functions, functionOf } = yield* load(
    matched,
    leaves,
    watched,
  );
  const deployment = yield* DeploymentKind.DeploymentKind;
  const visible: Omit<ManifestSection.GenerateInput, "sections"> = {
    mounts: input.mounts,
    files: input.files,
    functions,
    functionOf,
    modules,
    target,
    deployment,
    confectDirectory,
  };
  // `sections` is not enumerable, so a section that serializes its input
  // writes what it wrote before render got the keys.
  const generateInput = Object.defineProperty(visible, "sections", {
    value: input.sections,
  }) as ManifestSection.GenerateInput;
  const { contents, errors, groups } = yield* Effect.try({
    try: () => generate.render(generateInput),
    catch: failed,
  });
  yield* refuse(key, errors);
  const sources = yield* encodeSources(matched);
  return {
    modules,
    contents: Arr.join(
      [...headers[extension(generate.file)](key, sources, generate), contents],
      "\n",
    ),
    groups: yield* renderGroups(key, generate.file, groups, leaves).pipe(
      Effect.map(
        Arr.map(({ group, file, contents: body }) => ({
          group,
          file,
          contents: Arr.join(
            [header(key), `// Sources: ${sources}`, body],
            "\n",
          ),
        })),
      ),
    ),
  };
});

// A declaration file, `.d.ts` or `.d.<ext>.ts`, which no module runs.
const DECLARATION = /\.d(\.[^.]+)?\.ts$/;

/**
 * Whether `groups` is a plain object whose own enumerable string-keyed values
 * are all functions. Symbol keys and non-enumerable keys are not inspected.
 */
const isGroups = (
  groups: unknown,
): groups is Readonly<
  Record<string, (file: ManifestSection.GroupFile) => unknown>
> =>
  typeof groups === "object" &&
  groups !== null &&
  [Object.prototype, null].includes(Object.getPrototypeOf(groups)) &&
  Arr.every(
    Record.values(groups as Readonly<Record<string, unknown>>),
    (value) => typeof value === "function",
  );

/**
 * Each group's module from `groups`, at its file in `_generated`, as a POSIX
 * path, with the specifiers it imports by resolved from there. Codegen refuses
 * `groups` that is not a plain object of functions, `groups` on a `.json` or
 * `.md` file, which nothing imports, even when empty, a group that registers no
 * Convex function, since no registration file imports its module, an
 * `importPath` of anything but an existing `.ts` file in `confect/` that is not
 * a declaration file, given relative to `confect/`, of a file in `_generated`,
 * or of a file beside which a `.js` file of the same name stands, which esbuild
 * resolves the specifier to instead, and a module that is not a string.
 */
const renderGroups = Effect.fnUntraced(function* (
  key: string,
  file: string,
  groups: unknown,
  leaves: ReadonlyArray<Leaf>,
) {
  if (groups === undefined) return [];
  const refusal = (reason: string) =>
    InvalidManifestSectionError.make({ sectionKey: key, reason });
  if (!isGroups(groups))
    return yield* refusal(
      `returns groups that is not a plain object of functions by group path, such as { "tasks/assignment": ({ importPath }) => "..." }.`,
    );
  if (!isModule(file))
    return yield* refusal(
      `returns groups for confect/_generated/${file}, but registered functions import only a .ts file.`,
    );
  const entries = Arr.sort(
    Record.toEntries(groups),
    Order.mapInput(Order.String, ([name]: readonly [string, unknown]) => name),
  );
  const names = Arr.map(entries, ([name]) => name);
  const registered = pipe(
    leaves,
    Arr.filter((leaf) => RouteSpecs.registersConvex(leaf.spec)),
    Arr.map((leaf) => Arr.join(leaf.pathSegments, "/")),
    Arr.sort(Order.String),
  );
  const unknown = Arr.findFirst(names, (name) => !registered.includes(name));
  if (Option.isSome(unknown))
    return yield* refusal(
      `gives a file to the group ${quote(unknown.value)}, which registers no Convex function; name a group by its spec file's path in confect/ without .spec.ts, with / between directories, as each function's group gives it${registered.length === 0 ? "" : `, such as ${quote(registered[0])}`}.`,
    );
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  const stem = pipe(file, Str.slice(0, -".ts".length));
  return yield* Effect.forEach(entries, ([group, renderGroup]) =>
    Effect.gen(function* () {
      const relative = `${GROUPS}/${stem}/${group}.ts`;
      const directory = path.dirname(path.join(generated, relative));
      const refused = (to: unknown, why: string) =>
        refusal(
          `importPath(${typeof to === "string" ? quote(to) : String(to)}) for the group ${quote(group)} ${why}; pass the path of an existing .ts file relative to confect/, with its extension, such as "tasks.impl.ts".`,
        );
      // Each file `importPath` named, with the path it was given, checked once
      // the module is rendered.
      const named = new Map<string, string>();
      const importPath = (to: unknown) => {
        if (typeof to !== "string") throw refused(to, "takes no path");
        if (/^([\\/]|[A-Za-z]:)/.test(to))
          throw refused(to, "takes an absolute path");
        if (/[\\/]$/.test(to)) throw refused(to, "names a directory");
        const inside = path.relative(
          confectDirectory,
          path.resolve(confectDirectory, to),
        );
        if (
          inside === "" ||
          path.isAbsolute(inside) ||
          pipe(inside, Str.split(path.sep))[0] === ".."
        )
          throw refused(to, "leaves confect/");
        if (path.extname(inside) !== ".ts")
          throw refused(to, "names no .ts file");
        if (DECLARATION.test(path.basename(inside)))
          throw refused(to, "names a declaration file, which no module runs");
        if (pipe(toPosixPath(path, inside), Str.split("/"))[0] === "_generated")
          throw refused(
            to,
            "takes a source file under confect/, not a generated one in confect/_generated",
          );
        if (!named.has(inside)) named.set(inside, to);
        const target = toPosixPath(
          path,
          path.relative(directory, path.join(confectDirectory, inside)),
        );
        const bare = pipe(target, Str.slice(0, -".ts".length));
        return `${pipe(bare, Str.startsWith("./")) || pipe(bare, Str.startsWith("../")) ? bare : `./${bare}`}.js`;
      };
      const contents: unknown = yield* Effect.try({
        try: () => renderGroup({ importPath }),
        catch: (cause) =>
          Schema.is(InvalidManifestSectionError)(cause)
            ? cause
            : refusal(
                `generate failed for the group ${quote(group)}: ${String(cause)}`,
              ),
      });
      if (typeof contents !== "string")
        return yield* refusal(
          `the function for the group ${quote(group)} returned ${contents === null || contents === undefined ? String(contents) : `${typeof contents === "object" ? "an" : "a"} ${typeof contents}`}, not the text of its module.`,
        );
      for (const [inside, to] of named) {
        const at = path.join(confectDirectory, inside);
        const info = yield* Effect.option(fs.stat(at));
        if (Option.isNone(info) || info.value.type !== "File")
          return yield* refused(to, "names no file in confect/");
        // esbuild resolves a `.js` specifier to a `.js` file that exists
        // before it tries the `.ts` file; a directory of that name it skips.
        const js = `${pipe(inside, Str.slice(0, -".ts".length))}.js`;
        const shadow = yield* Effect.option(
          fs.stat(path.join(confectDirectory, js)),
        );
        if (Option.isSome(shadow) && shadow.value.type === "File")
          return yield* refusal(
            `importPath(${quote(to)}) for the group ${quote(group)} names confect/${toPosixPath(path, inside)}, but the specifier it gives resolves to confect/${toPosixPath(path, js)} instead; rename one of them.`,
          );
      }
      return { group, file: relative, contents };
    }),
  );
});

/**
 * The `.ts` files in `confect/_generated` a section wrote, which carry its
 * header.
 *
 * @internal
 */
export const written = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  if (!(yield* fs.exists(generated))) return [];
  const directory = yield* fs.readDirectory(generated);
  return yield* Effect.filter(
    Arr.filter(directory, (file) => pipe(file, Str.endsWith(".ts"))),
    (file) =>
      fs
        .readFileString(path.join(generated, file))
        .pipe(Effect.map((contents) => pipe(contents, Str.startsWith(PREFIX)))),
  );
});

/**
 * Write `files`, sorted, as a JSON array to `recordPath`.
 */
const writeRecord = (recordPath: string, files: ReadonlyArray<string>) =>
  encodeSources([...files].sort()).pipe(
    Effect.flatMap((sources) => writeFileStringAndLog(recordPath, sources)),
  );

const record = Effect.fnUntraced(function* (name: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const file = path.join(confectDirectory, "_generated", name);
  const none: ReadonlyArray<string> = [];
  if (!(yield* fs.exists(file))) return none;
  const fileContents = yield* fs.readFileString(file);
  return Option.getOrElse(decodeSources(fileContents), () => none);
});

/**
 * The record's file names and the digest of the bytes codegen wrote to each,
 * empty when there is no record. A record that does not decode, or names a file
 * no section could claim, fails codegen rather than being guessed at.
 */
const readOwned = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const file = path.join(confectDirectory, "_generated", RECORD);
  const none: Readonly<Record<string, string>> = {};
  if (!(yield* fs.exists(file))) return none;
  const projectRoot = yield* ProjectRoot.get;
  const invalid = (reason: string) =>
    InvalidSectionFilesRecordError.make({
      recordPath: toPosixPath(path, path.relative(projectRoot, file)),
      reason,
    });
  const contents = yield* fs.readFileString(file);
  const owned = decodeOwned(contents);
  if (Option.isNone(owned))
    return yield* invalid(
      "it is not a JSON object from file names to sha256 digests",
    );
  const foreign = Arr.findFirst(
    Record.keys(owned.value),
    (name) => !tracked(name),
  );
  if (Option.isSome(foreign))
    return yield* invalid(
      `it lists ${quote(foreign.value)}, which no section can claim`,
    );
  return owned.value;
});

/**
 * Replace the record with `owned`, sorted, by renaming a file written beside
 * it, so a run cut short leaves the old record or the new one and never part of
 * one. An empty `owned` removes the record.
 */
const writeOwned = Effect.fnUntraced(function* (
  owned: Readonly<Record<string, string>>,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const file = path.join(confectDirectory, "_generated", RECORD);
  const names = Record.keys(owned).sort();
  if (names.length === 0) return yield* removePathIfExists(file);
  const contents = stringify(
    Record.fromEntries(Arr.map(names, (name) => [name, owned[name]] as const)),
  );
  const existed = yield* fs.exists(file);
  if (existed && (yield* fs.readFileString(file)) === contents) return;
  const pending = path.join(confectDirectory, "_generated", `.${RECORD}.tmp`);
  yield* fs.writeFileString(pending, contents);
  yield* fs.rename(pending, file);
  yield* existed ? logFileModified(file) : logFileAdded(file);
});

/**
 * The `confect/` files the declared sections' `generate` and `verify` matched
 * and the `confect/` files those import, as recorded by the last codegen run
 * that loaded them.
 *
 * @internal
 */
export const inputs = Effect.map(
  Effect.all([record(INPUTS), record(VERIFY_INPUTS)]),
  ([rendered, verified]) => [...new Set([...rendered, ...verified])].sort(),
);

/**
 * The first path from `_generated/sections` down to the group file `file` that
 * holds something codegen did not write there: anything but a directory above
 * it, or at `file` anything but a file `recorded` lists or a file holding
 * `contents`, the bytes this run writes there.
 */
const unwritten = Effect.fnUntraced(function* (
  file: string,
  contents: string,
  recorded: Readonly<Record<string, string>>,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  const segments = pipe(file, Str.split("/"));
  for (let depth = 1; depth <= segments.length; depth++) {
    const at = Arr.take(segments, depth);
    const info = yield* Effect.option(fs.stat(path.join(generated, ...at)));
    if (Option.isNone(info)) return Option.none<string>();
    const last = depth === segments.length;
    if (!last) {
      if (info.value.type !== "Directory")
        return Option.some(Arr.join(at, "/"));
      continue;
    }
    if (info.value.type !== "File") return Option.some(file);
    if (Record.has(recorded, file)) return Option.none<string>();
    const bytes = yield* fs.readFile(path.join(generated, file));
    if (digest(bytes) !== digest(contents)) return Option.some(file);
  }
  return Option.none<string>();
});

/**
 * Write each claimed file into `confect/_generated` once every section the
 * declared backend names has rendered for its target; an undeclared backend
 * renders none. Every section renders before codegen fails with the first error
 * after logging the rest. The record of section inputs is written either way,
 * keeping the previous inputs after a failure, so `confect dev` sees the fix.
 * Returns the claimed file names, the ones the HTTP router imports, the ones
 * every registered function imports, the modules each section key matched, the
 * files of the sections that wrap crons, in the order `App.make` declares them,
 * the file of the section that wraps the schema, if any, each group's own
 * modules, by group path, as paths relative to `_generated`, which only that
 * group's registered functions import, after the rest, and those paths sorted.
 * The router and registered functions import the file of the section that sets
 * `importedFirst` before the rest. Before it writes a `.json` or `.md` file it
 * records the file with the digest of the bytes it is about to write, so a run
 * that fails later still lets the next one remove it. It records a group's
 * module with its digest only after writing it, so the record never lists a
 * module codegen has not written. A group's module whose path holds anything
 * but a directory above it, or at it anything but a file the record lists or
 * one already holding the bytes this run writes, is refused after the record of
 * section inputs is written and before any section file, group module or
 * `sectionFiles.json` is.
 *
 * @internal
 */
export const sync = Effect.fnUntraced(function* (
  backend: Option.Option<Backend>,
  leaves: ReadonlyArray<Leaf>,
  mounts: ManifestSection.GenerateInput["mounts"],
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  const claimed = Option.isSome(backend)
    ? yield* Effect.map(
        Effect.fromResult(claims(backend.value.sections)),
        Arr.map((claim) => ({ claim, target: backend.value.target })),
      )
    : [];
  const files = claimed.length === 0 ? [] : yield* sourceFiles;
  const sections = Option.match(backend, {
    onNone: () => [],
    onSome: (declared) => Arr.map(declared.sections, ({ key }) => key),
  });
  const watched = new Set<string>();
  const [rendered, failures] = yield* Effect.partition(
    claimed,
    ({ claim, target }) =>
      render(claim, target, leaves, { mounts, files, sections }, watched).pipe(
        Effect.map((output) => ({ ...claim, ...output })),
      ),
  );
  if (failures.length > 0)
    for (const file of yield* record(INPUTS)) watched.add(file);
  yield* claimed.length === 0
    ? removePathIfExists(path.join(generated, INPUTS))
    : writeRecord(path.join(generated, INPUTS), [...watched]);
  const [error, ...more] = failures;
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
  const fs = yield* FileSystem.FileSystem;
  const names = Arr.map(rendered, ({ generate }) => generate.file);
  const recorded = yield* readOwned;
  const groupFiles = Arr.flatMap(rendered, ({ key, groups }) =>
    Arr.map(groups, (group) => ({ key, ...group })),
  );
  for (const { key, group, file, contents } of groupFiles) {
    const blocker = yield* unwritten(file, contents, recorded);
    if (Option.isSome(blocker))
      return yield* InvalidManifestSectionError.make({
        sectionKey: key,
        reason: `gives the group ${quote(group)} confect/_generated/${file}, but codegen did not write what is at confect/_generated/${blocker.value}; move or delete it.`,
      });
  }
  const owned = {
    ...recorded,
    ...Record.fromEntries(
      Arr.flatMap(rendered, ({ generate, contents }) =>
        isModule(generate.file)
          ? []
          : [[generate.file, digest(contents)] as const],
      ),
    ),
  };
  if (Record.size(owned) > 0) yield* writeOwned(owned);
  for (const { generate, contents } of rendered)
    yield* writeFileStringAndLog(path.join(generated, generate.file), contents);
  // A group module is compared by its bytes, so the file holds exactly the
  // bytes whose digest the record lists.
  for (const { file, contents } of groupFiles) {
    const target = path.join(generated, file);
    yield* fs.makeDirectory(path.dirname(target), { recursive: true });
    const existed = yield* fs.exists(target);
    const existing = existed ? yield* fs.readFile(target) : undefined;
    if (existing !== undefined && digest(existing) === digest(contents))
      continue;
    yield* fs.writeFileString(target, contents);
    yield* existed ? logFileModified(target) : logFileAdded(target);
  }
  // The group modules enter the record once they are written.
  const withGroups = {
    ...owned,
    ...Record.fromEntries(
      Arr.map(
        groupFiles,
        ({ file, contents }) => [file, digest(contents)] as const,
      ),
    ),
  };
  if (Record.size(withGroups) > 0) yield* writeOwned(withGroups);
  const groups = new Map<string, Array<string>>();
  for (const { group, file } of groupFiles)
    groups.set(group, [...(groups.get(group) ?? []), file]);
  const imported = Arr.flatMap(rendered, ({ generate }) =>
    generate.importedByFunctions === false || !isModule(generate.file)
      ? []
      : [generate.file],
  );
  const first = Arr.findFirst(
    rendered,
    ({ generate }) => generate.importedFirst === true,
  ).pipe(Option.map(({ generate }) => generate.file));
  const firstOf = (imports: ReadonlyArray<string>) =>
    Option.match(first, {
      onNone: () => imports,
      onSome: (file) => [
        file,
        ...Arr.filter(imports, (other) => other !== file),
      ],
    });
  return {
    modules: new Map(Arr.map(rendered, ({ key, modules }) => [key, modules])),
    files: names,
    http: firstOf(Arr.filter(names, isModule)),
    functions: firstOf(imported),
    crons: Option.isNone(backend)
      ? []
      : Arr.flatMap(backend.value.sections, ({ section: { generate } }) =>
          generate?.wrapsCrons === true ? [generate.file] : [],
        ),
    schema: Arr.findFirst(
      rendered,
      ({ generate }) => generate.wrapsSchema === true,
    ).pipe(Option.map(({ generate }) => generate.file)),
    groups,
    groupFiles: Arr.map(groupFiles, ({ file }) => file).sort(),
  };
});

/**
 * Run each declared section's `verify` once every `_generated` file exists:
 * bundle the `confect/` files its `match` selects as codegen bundles a
 * declaration, and hand their exports, the functions, the mounts, the target,
 * the deployment kind and the declared guard's name to its `check`. Every
 * section checks before codegen fails with the first refusal after logging the
 * rest. The files each loaded are recorded as section inputs, keeping the
 * previous ones after a failure, so `confect dev` checks again when one
 * changes.
 *
 * @internal
 */
export const verify = Effect.fnUntraced(function* (
  backend: Option.Option<Backend>,
  leaves: ReadonlyArray<Leaf>,
  input: Pick<ManifestSection.VerifyInput, "mounts" | "guard">,
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const recorded = path.join(confectDirectory, "_generated", VERIFY_INPUTS);
  const checks = Option.match(backend, {
    onNone: () => [],
    onSome: ({ sections }) =>
      Arr.flatMap(sections, ({ key, section }) =>
        section.generate?.verify === undefined
          ? []
          : [{ key, verifier: section.generate.verify }],
      ),
  });
  if (Option.isNone(backend) || checks.length === 0)
    return yield* removePathIfExists(recorded);
  const { target } = backend.value;
  const deployment = yield* DeploymentKind.DeploymentKind;
  const files = yield* sourceFiles;
  const watched = new Set<string>();
  const [, failures] = yield* Effect.partition(checks, ({ key, verifier }) =>
    Effect.gen(function* () {
      const failed = (cause: unknown) =>
        InvalidManifestSectionError.make({
          sectionKey: key,
          reason: `verify failed: ${String(cause)}`,
        });
      const matched = yield* Effect.try({
        try: () => Arr.filter(files, (file) => verifier.match(file)),
        catch: failed,
      });
      const { modules, functions, functionOf } = yield* load(
        matched,
        leaves,
        watched,
        [ConvexConfig.componentConfigPlugin(path)],
      );
      const tryValue = yield* Effect.try({
        try: () =>
          verifier.check({
            ...input,
            functions,
            functionOf,
            modules,
            target,
            deployment,
          }),
        catch: failed,
      });
      yield* refuse(key, tryValue);
    }),
  );
  if (failures.length > 0)
    for (const file of yield* record(VERIFY_INPUTS)) watched.add(file);
  yield* writeRecord(recorded, [...watched]);
  const [error, ...more] = failures;
  for (const other of more) yield* logCodegenError(other);
  if (error !== undefined) return yield* error;
});

/**
 * Remove `directory` and each parent up to `_generated` while it is empty.
 */
const removeEmptyParents = Effect.fnUntraced(function* (directory: string) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const generated = path.join(confectDirectory, "_generated");
  let current = directory;
  while (
    current !== generated &&
    (yield* fs.exists(current)) &&
    (yield* fs.readDirectory(current)).length === 0
  ) {
    yield* fs.remove(current, { recursive: true });
    current = path.dirname(current);
  }
});

/**
 * Remove each file a section wrote that is not in `files` or `groupFiles`: a
 * `.ts` file directly in `_generated` that carries a section's header, and a
 * file the record lists, a `.json` or `.md` file or a group's module, that is
 * still a file holding the bytes it records, with the directories a removed
 * module leaves empty. A listed file holding other bytes was edited, or never
 * written, so it stays, with a warning, and drops out of the record, as does
 * anything but a file at a listed path, which codegen does not read. A group's
 * module leaves the record before its file is removed, so the record never
 * lists a module codegen removed; a `.json` or `.md` file leaves it after. The
 * record then lists only the claimed files, and goes once none is left. Codegen
 * runs this after it rewrites the registration files and the HTTP router, so a
 * run that fails earlier leaves no import of a removed file.
 *
 * @internal
 */
export const removeUnclaimed = Effect.fnUntraced(function* (
  files: ReadonlyArray<string>,
  groupFiles: ReadonlyArray<string>,
) {
  const path = yield* Path.Path;
  const confectDirectory = yield* ConfectDirectory.get;
  const projectRoot = yield* ProjectRoot.get;
  const generated = path.join(confectDirectory, "_generated");
  const fs = yield* FileSystem.FileSystem;
  const remove = Effect.fnUntraced(function* (file: string) {
    yield* removePathIfExists(path.join(generated, file));
    yield* logFileRemoved(path.join(generated, file));
  });
  const claimed = (file: string) =>
    files.includes(file) || groupFiles.includes(file);
  const owned = yield* readOwned;
  for (const file of yield* written)
    if (!files.includes(file)) yield* remove(file);
  const removable: Array<string> = [];
  for (const [file, recorded] of Record.toEntries(owned)) {
    const target = path.join(generated, file);
    if (claimed(file)) continue;
    const info = yield* Effect.option(fs.stat(target));
    if (Option.isNone(info)) continue;
    const shown = toPosixPath(path, path.relative(projectRoot, target));
    if (info.value.type !== "File") {
      yield* logWarn(
        `${shown} is not the file codegen last wrote there, so codegen keeps it and stops tracking it.`,
      );
      continue;
    }
    const bytes = yield* fs.readFile(target);
    if (digest(bytes) !== recorded) {
      yield* logWarn(
        `${shown} does not hold what codegen last wrote there, so codegen keeps it and stops tracking it.`,
      );
      continue;
    }
    removable.push(file);
  }
  yield* writeOwned(
    Record.filter(owned, (_, file) => claimed(file) || !isGroupFile(file)),
  );
  for (const file of removable) {
    yield* remove(file);
    if (isGroupFile(file))
      yield* removeEmptyParents(path.dirname(path.join(generated, file)));
  }
  yield* writeOwned(Record.filter(owned, (_, file) => claimed(file)));
});
