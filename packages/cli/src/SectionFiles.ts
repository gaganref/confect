// The `.json` and `.md` files the sections wrote, and the modules they wrote for
// groups, each with the digest of the bytes written. Codegen finds the `.ts`
// files directly in `_generated` by their header; this record is how it knows
// the rest, and the digest is how it knows a file still holds what codegen
// wrote.
const RECORD = "sectionFiles.json";
// The directory in `_generated` holding each section's module for a group, at
// `<section file without .ts>/<group path>.ts`.
const GROUPS = "sections";

/**
 * The files codegen writes directly in `confect/_generated`, current and
 * legacy, which no section may claim.
 */
export const builtIn: ReadonlySet<string> = new Set([
  ...Arr.map(
    pipe(
      `spec schema convexSchema id components component refs docs services manifest
  auth.providers testing api nodeApi impl nodeImpl nodeSpec registeredFunctions
  nodeRegisteredFunctions routes`,
      Str.split(/\s+/),
    ),
    (name) => `${name}.ts`,
  ),
  INPUTS,
  VERIFY_INPUTS,
  RECORD,
  "openapi.json",
]);

const NAME = /^[\w-]+\.(ts|json|md)$/;
const GENERATED = "Generated by `confect codegen` from the manifest section ";
const PREFIX = `// ${GENERATED}`;
const header = (key: string) => `${PREFIX}${quote(key)}. Do not edit.`;
// The second line of a file registered functions do not import.
const OUTSIDE_FUNCTIONS = "// Registered functions do not import this file.";
// The second line of the file registered functions import first.
const IMPORTED_FIRST = "// Registered functions import this file first.";
const Sources = Schema.String.pipe(Schema.Array, Schema.fromJsonString);
const encodeSources = (sources: ReadonlyArray<string>) =>
  Schema.encodeEffect(Sources)(sources).pipe(Effect.orDie);
const decodeSources = Schema.decodeUnknownOption(Sources);
const Owned = Schema.Record(
  Schema.String,
  Schema.String.check(Schema.isPattern(/^sha256:[0-9a-f]{64}$/)),
).pipe(Schema.fromJsonString);
const decodeOwned = Schema.decodeUnknownOption(Owned);
const digest = (bytes: string | Uint8Array) =>
  `sha256:${createHash("sha256").update(bytes).digest("hex")}`;

/**
 * Whether `file` is a module registered functions, the HTTP router and
 * `convex/crons.ts` can import. Only a `.ts` file is.
 */
const isModule = (file: string) => pipe(file, Str.endsWith(".ts"));

/**
 * Whether `file`, a POSIX path relative to `_generated`, is where a section's
 * module for a group goes: `sections/<section file without .ts>/<group>.ts`.
 */
const isGroupFile = (file: string) => {
  const [root, stem, ...rest] = pipe(file, Str.split("/"));
  return (
    root === GROUPS &&
    stem !== undefined &&
    NAME.test(`${stem}.ts`) &&
    rest.length > 0 &&
    pipe(Arr.join(rest, "/"), Str.endsWith(".ts")) &&
    Arr.every(rest, (segment) => !["", ".", ".."].includes(segment))
  );
};

/**
 * Whether a section could write `file` and codegen would track it in the
 * record: a `.json` or `.md` file directly in `_generated` that codegen does
 * not write itself, or a group's module.
 */
const tracked = (file: string) =>
  (NAME.test(file) && !isModule(file) && !builtIn.has(file)) ||
  isGroupFile(file);

/**
 * The lines codegen writes above what `render` returned, by the claimed file's
 * extension. A `.json` file can hold no comment, so it gets none.
 */
const headers = {
  ts: (key: string, sources: string, generate: ManifestSection.Generate) => [
    header(key),
    ...(generate.importedByFunctions === false ? [OUTSIDE_FUNCTIONS] : []),
    ...(generate.importedFirst === true ? [IMPORTED_FIRST] : []),
    `// Sources: ${sources}`,
  ],
  md: (key: string, sources: string) => [
    `<!-- ${GENERATED}${quote(key)}. Do not edit. -->`,
    `<!-- Sources: ${sources} -->`,
  ],
  json: () => [],
};

const extension = (file: string) =>
  pipe(file, Str.split(".")).at(-1) as keyof typeof headers;

