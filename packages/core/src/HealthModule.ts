import * as Option from "effect/Option";
import * as Schema from "effect/Schema";
import * as String from "effect/String";

/**
 * The exact health module codegen writes. Keep this file unformatted and
 * unedited after generation so deployment tooling can verify its complete
 * contents.
 */
export const render = (digest: string): string =>
  `// Generated by \`confect codegen\` from confect/app.ts. Do not edit.
import { internalQueryGeneric } from "convex/server";
import { v } from "convex/values";

export const digest = internalQueryGeneric({
  args: {},
  returns: v.string(),
  handler: () => ${Schema.encodeSync(Schema.fromJsonString(Schema.String))(digest)},
});
`;

/**
 * Read the digest only from an exact generated module, allowing CRLF line
 * endings. Any edit, extra text, or missing module reads as not generated.
 */
export const read = (contents: string): Option.Option<string> => {
  const normalized = String.replace(/\r\n?/g, "\n")(contents);
  const found = /^  handler: \(\) => ("(?:[^"\\]|\\.)*"),$/m.exec(normalized);
  return found === null
    ? Option.none()
    : Schema.decodeOption(Schema.fromJsonString(Schema.String))(found[1]!).pipe(
        Option.filter((digest) => normalized === render(digest)),
      );
};
