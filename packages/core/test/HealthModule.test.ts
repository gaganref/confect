import * as Str from "effect/String";
import * as HealthModule from "@confect/core/HealthModule";
import { expect, it } from "@effect/vitest";
import * as Option from "effect/Option";

it("reads only the generated module, accepting LF and CRLF", () => {
  const digest = "sha256:abc";
  const contents = HealthModule.render(digest);
  expect(HealthModule.read(contents)).toEqual(Option.some(digest));
  expect(HealthModule.read(Str.replaceAll("\n", "\r\n")(contents))).toEqual(
    Option.some(digest),
  );
  expect(HealthModule.read(digest)).toEqual(Option.none());
  expect(
    HealthModule.read(
      `/*\n handler: () => "${digest}",\n*/\n${HealthModule.render("sha256:other")}`,
    ),
  ).toEqual(Option.none());
});

it("pins the generated health module text", () => {
  expect(HealthModule.render("sha256:abc"))
    .toBe(`// Generated by \`confect codegen\` from confect/app.ts. Do not edit.
import { internalQueryGeneric } from "convex/server";
import { v } from "convex/values";

export const digest = internalQueryGeneric({
  args: {},
  returns: v.string(),
  handler: () => "sha256:abc",
});
`);
});

it("refuses a lone carriage return", () => {
  const contents = Str.replace("\n", "\r")(HealthModule.render("sha256:abc"));
  expect(HealthModule.read(contents)).toEqual(Option.none());
});
